// Build /pt from the English structure and reviewed Brazilian Portuguese copy.
// Usage: node constitution/tools/build-pt.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { swapInner, once, attr } from './translation-utils.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORIGIN = 'https://constitution.design';
const PT = JSON.parse(readFileSync(join(ROOT, 'tools/pt-BR.json'), 'utf8'));
const TITLE = 'A Constituição do Designer';
const DESCRIPTION = 'Um modelo para repensar o que faz de alguém um designer na era da IA, construído sobre os fundamentos que Walter Gropius estabeleceu para a Bauhaus em 1922.';
const OG_ALT = 'A Constituição do Designer, entre dois ramos de oliveira.';
const ALT = 'Cinco anéis concêntricos organizam o modelo: a base, estudos, materiais, o que permanece humano e, no centro, construir. Os conceitos de cada anel são explicados nos capítulos a seguir.';

let html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const keys = [...html.matchAll(/data-i18n="(t\d+)"/g)].map((m) => m[1]);
if (keys.length !== Object.keys(PT).length || keys.some((key) => !PT[key])) {
  throw new Error('English markers and Portuguese copy must match completely');
}
for (const key of keys) html = swapInner(html, key, PT[key]);
html = once(html, '<html lang="en">', '<html lang="pt-BR">');
html = html.replace(/<title>[^<]*<\/title>/, `<title>${TITLE}, por PabloZarate™</title>`);
html = html.replace(/(<meta name="description" content=")[^"]*(">)/, `$1${attr(DESCRIPTION)}$2`);
html = once(html, `<link rel="canonical" href="${ORIGIN}/">`, `<link rel="canonical" href="${ORIGIN}/pt">`);
for (const platform of ['og', 'twitter']) {
  const attribute = platform === 'og' ? 'property' : 'name';
  for (const [key, value] of Object.entries({ title: TITLE, description: PT.t102, image: `${ORIGIN}/assets/img/og-pt.jpg` })) {
    html = html.replace(new RegExp(`(<meta ${attribute}="${platform}:${key}" content=")[^"]*(">)`), `$1${attr(value)}$2`);
  }
}
html = once(html, `<meta property="og:url" content="${ORIGIN}/">`, `<meta property="og:url" content="${ORIGIN}/pt">`);
html = html.replace(/(<meta property="og:site_name" content=")[^"]*(">)/, `$1${TITLE}$2`);
html = html.replace(/(<meta property="og:image:alt" content=")[^"]*(">)/, `$1${attr(OG_ALT)}$2`);
html = once(html, `<meta name="twitter:image" content="${ORIGIN}/assets/img/og-pt.jpg">`, `<meta name="twitter:image" content="${ORIGIN}/assets/img/og-pt.jpg">\n<meta name="twitter:image:alt" content="${attr(OG_ALT)}">`);
html = once(html, '<meta property="og:locale" content="en_US">', '<meta property="og:locale" content="pt_BR">');
html = once(html, '<meta property="og:locale:alternate" content="pt_BR">', '<meta property="og:locale:alternate" content="en_US">');
html = once(html, 'src="assets/img/approved-en.png"', 'src="assets/img/approved-pt.png"');
html = html.replace(/( alt=")[^"]*(" data-i18n-alt="alt")/, `$1${attr(ALT)}$2`);
html = once(html, 'role="group" aria-label="Language"', 'role="group" aria-label="Idioma"');
html = once(html, 'aria-label="Rings of the model"', 'aria-label="Anéis do modelo"');
html = html.replace(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/, (s, json) => {
  const data = JSON.parse(json);
  delete data.workTranslation;
  Object.assign(data, {
    '@id': `${ORIGIN}/pt#essay`, headline: TITLE, alternativeHeadline: 'The Designer’s Constitution',
    description: DESCRIPTION, url: `${ORIGIN}/pt`, image: `${ORIGIN}/assets/img/og-pt.jpg`,
    inLanguage: 'pt-BR', translationOfWork: { '@id': `${ORIGIN}/#essay` },
    isBasedOn: { ...data.isBasedOn, name: 'Diagrama do currículo da Bauhaus' },
    about: ['Design', 'Bauhaus', 'Liderança em design', 'Inteligência artificial'],
    keywords: 'design, designer, Bauhaus, Walter Gropius, IA, liderança em design, ofício, construir',
    mainEntityOfPage: `${ORIGIN}/pt`,
  });
  return `<script type="application/ld+json">${JSON.stringify(data)}</script>`;
});
// Keep source credit without inventing a translator identity or a licence.
html = once(html, '</footer>', '<p class="foot-small">Versão em português revisada a partir de uma <a href="https://constitutiondesign.vercel.app/">tradução da comunidade</a>.</p>\n</footer>');
html = html.replace(/(href|src)="assets\//g, '$1="../assets/');
html = once(html, "l.href = 'assets/fonts/' + f;", "l.href = '../assets/fonts/' + f;");
html = once(html, 'data-lang="en" aria-pressed="true"', 'data-lang="en" aria-pressed="false"');
html = once(html, 'data-lang="pt" aria-pressed="false"', 'data-lang="pt" aria-pressed="true"');
html = once(html, '<!doctype html>', '<!doctype html>\n<!-- Generated by tools/build-pt.mjs from index.html and tools/pt-BR.json. -->');
const target = join(ROOT, 'pt/index.html');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch {}
  if (current !== html) throw new Error('pt/index.html is out of date: run node constitution/tools/build-pt.mjs');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, html);
}
